def report_export_pdf(report: dict[str, Any], sections_html: list[str]) -> tuple[Path, str]:
    """PDF export using fpdf2 (Unicode-compatible, production-grade)."""
    from fpdf import FPDF

    out = settings.export_dir
    out.mkdir(parents=True, exist_ok=True)
    fname = f"report_{uuid.uuid4().hex[:10]}.pdf"
    path = out / fname

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    pdf.add_font("DejaVu", "", str(_font_path(False)))
    pdf.add_font("DejaVu", "B", str(_font_path(True)))
    pdf.set_font("DejaVu", "B", 20)
    pdf.cell(0, 12, report.get("name", "Report"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("DejaVu", "", 9)
    pdf.set_text_color(120, 120, 128)
    pdf.cell(0, 8, f"Generated by Nexus Data \u00b7 {report.get('generated_at', '')}", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(28, 28, 30)
    pdf.ln(6)

    for block in sections_html:
        _pdf_block(pdf, block)
    pdf.output(str(path))
    return path, fname


def _font_path(bold: bool) -> Path:
    repo_assets = Path(__file__).resolve().parent.parent.parent / "assets" / "fonts"
    if bold:
        candidates = [
            repo_assets / "DejaVuSans-Bold.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
            "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf",
            "/usr/share/fonts/google-carlito-fonts/Carlito-Bold.ttf",
            "/usr/share/fonts/google-droid-sans-fonts/DroidSans-Bold.ttf",
        ]
    else:
        candidates = [
            repo_assets / "DejaVuSans.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/google-carlito-fonts/Carlito-Regular.ttf",
            "/usr/share/fonts/google-droid-sans-fonts/DroidSans.ttf",
        ]
    for c in candidates:
        if Path(c).exists():
            return Path(c)
    return candidates[0]


def _pdf_block(pdf: "FPDF", html: str) -> None:
    import re
    tokens = re.split(r"(<[^>]+>|</[^>]+>)", html)
    page_w = pdf.w - pdf.l_margin - pdf.r_margin
    pdf.set_font("DejaVu", "", 11)
    pdf.set_fill_color(245, 245, 247)
    for tok in tokens:
        if tok.startswith("<") or not tok.strip():
            continue
        text = _plain_text(tok).strip()
        if not text:
            continue
        if text.startswith("KPI|"):
            _, label, value = text.split("|", 2)
            pdf.set_x(pdf.l_margin)
            x = pdf.get_x()
            lw = pdf.get_string_width(label)
            vw = pdf.get_string_width(value)
            tw = max(lw, vw) + 20
            pdf.rect(x, pdf.get_y(), min(tw, 190), 20, style="DF")
            pdf.set_xy(x + 7, pdf.get_y() + 4)
            pdf.set_font("DejaVu", "B", 13)
            pdf.set_text_color(28, 28, 30)
            pdf.cell(min(tw, 190) - 14, 7, value)
            pdf.set_font("DejaVu", "", 8)
            pdf.set_text_color(110, 110, 118)
            pdf.set_xy(x + 7, pdf.get_y() + 7)
            pdf.cell(min(tw, 190) - 14, 5, label)
            pdf.set_text_color(28, 28, 30)
            pdf.set_x(pdf.l_margin)
            pdf.set_y(pdf.get_y() + 14)
        elif text.startswith("H1|"):
            pdf.set_x(pdf.l_margin)
            pdf.set_font("DejaVu", "B", 15)
            pdf.ln(3)
            pdf.multi_cell(page_w, 9, text[3:])
        elif text.startswith("H2|"):
            pdf.set_x(pdf.l_margin)
            pdf.set_font("DejaVu", "B", 13)
            pdf.ln(2)
            pdf.multi_cell(page_w, 8, text[3:])
        elif text.startswith("BUL|"):
            pdf.set_x(pdf.l_margin)
            pdf.set_font("DejaVu", "", 11)
            pdf.multi_cell(page_w, 7, "\u2022 " + text[4:])
        elif text.startswith("|"):
            raw_lines = [l for l in text[1:].strip().split("\n") if l.strip()]
            if not raw_lines:
                continue
            pdf.set_x(pdf.l_margin)
            rows = [l.split("\t") for l in raw_lines]
            ncols = max(len(r) for r in rows)
            for r in rows:
                if len(r) < ncols:
                    r.extend([""] * (ncols - len(r)))
            widths = []
            for ci in range(ncols):
                w = max(pdf.get_string_width((r[ci] or "")[:30]) for r in rows)
                widths.append(min(max(w + 4, 12), page_w))
            total = sum(widths)
            if total > page_w:
                scale = page_w / total
                widths = [(ww * scale) for ww in widths]
            header = rows[0]
            for i, r in enumerate(rows):
                if pdf.get_y() + 9 > pdf.h - 30:
                    pdf.add_page()
                    pdf.set_font("DejaVu", "B", 9)
                    for ci in range(ncols):
                        pdf.cell(widths[ci], 7, (header[ci] or "")[:30], border=1)
                    pdf.ln()
                style = "B" if i == 0 else ""
                pdf.set_font("DejaVu", style, 9)
                alt = i % 2 == 0 and i > 0
                fill = alt or i == 0
                if fill:
                    pdf.set_fill_color(245, 245, 247)
                else:
                    pdf.set_fill_color(255, 255, 255)
                for ci in range(ncols):
                    pdf.cell(widths[ci], 7, (r[ci] or "")[:30], border=1, fill=fill)
                pdf.ln()
            pdf.set_x(pdf.l_margin)
            pdf.ln(2)
        else:
            pdf.set_x(pdf.l_margin)
            pdf.set_font("DejaVu", "", 11)
            pdf.multi_cell(page_w, 7, text)


def _plain_text(html: str) -> str:
    import re
    text = re.sub(r"<[^>]+>", "", html)
    text = re.sub(r"&middot;", "\u00b7", text)
    text = re.sub(r"&amp;", "&", text)
    text = re.sub(r"\u00a0", " ", text)
    return text.strip()