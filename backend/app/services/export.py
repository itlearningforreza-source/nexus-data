EXPORT_FORMATS = {"csv", "tsv", "json", "xlsx", "parquet", "html"}
SAFE_METRICS = {"sum", "avg", "mean", "count", "min", "max", "median", "std"}


def export_dataframe(df: pd.DataFrame, fmt: str) -> tuple[Path, str]:
    fmt = fmt.lower()
    if fmt not in EXPORT_FORMATS:
        raise DataProcessingError(f"Unsupported export format '{fmt}'.")
    out = settings.export_dir
    out.mkdir(parents=True, exist_ok=True)
    fname = f"nexus_export_{uuid.uuid4().hex[:10]}.{fmt}"
    path = out / fname
    try:
        if fmt == "csv":
            df.to_csv(path, index=False)
        elif fmt == "tsv":
            df.to_csv(path, sep="\t", index=False)
        elif fmt == "json":
            records = df.head(50000).where(pd.notna(df), None)
            path.write_text(json.dumps({"columns": [str(c) for c in df.columns], "rows": records.values.tolist()}, default=str))
        elif fmt == "xlsx":
            df.head(100000).to_excel(path, index=False, engine="openpyxl")
        elif fmt == "parquet":
            df.to_parquet(path, index=False)
        elif fmt == "html":
            path.write_text(df.head(10000).to_html(classes="nexus-table", index=False))
    except DataProcessingError:
        raise
    except Exception as exc:  # noqa: BLE001
        raise DataProcessingError(
            f"Export to {fmt} failed.", detail={"error": str(exc)}
        ) from exc
    return path, fname


def export_sql_result(columns: list[str], rows: list[list[Any]], fmt: str) -> tuple[Path, str]:
    df = pd.DataFrame(rows, columns=columns)
    return export_dataframe(df, fmt)


